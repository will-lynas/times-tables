import { expect, test, type Page } from '@playwright/test'

async function startOrdered(page: Page) {
  await page.goto('/')
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
}

test('keeps saved partials separate from full-grid scores after reload', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('times-tables.scores', JSON.stringify({ version: 1, scores: [
    { id: 'legacy-perfect', mode: 'ordered', correct: 144, total: 144, elapsedMs: 1000, completedAt: '2026-01-01T00:00:00.000Z' },
  ] })))
  await startOrdered(page)
  await page.getByRole('textbox', { name: '1 × 1', exact: true }).fill('1')
  await page.getByRole('button', { name: 'Finish early', exact: true }).click()
  const partials = page.getByRole('table', { name: 'Partial results', exact: true })
  await expect(partials.getByRole('row')).toHaveCount(2)
  await expect(partials).toContainText('1 / 144')
  await expect(partials).toContainText('1 / 1')
  await expect(partials).toContainText('100%')
  await expect(page.getByRole('table', { name: 'High scores', exact: true }).getByRole('row')).toHaveCount(2)
  await expect(page.getByText('Fastest perfect: 0:01.0', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await expect(partials.getByRole('row')).toHaveCount(2)
  await expect(partials).toContainText('1 / 144')
  await expect(page.getByText('Fastest perfect: 0:01.0', { exact: true })).toBeVisible()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!))
  expect(saved.version).toBe(3)
  expect(saved.scores).toHaveLength(2)
  expect(saved.scores[0]).toMatchObject({ id: 'legacy-perfect', status: 'complete', attempted: 144, size: 12 })
  expect(saved.scores[1]).toMatchObject({ status: 'partial', attempted: 1, correct: 1 })
  await page.getByRole('radio', { name: 'Shuffled', exact: true }).click()
  await expect(partials.getByRole('row')).toHaveCount(2)
  await page.getByRole('combobox', { name: 'Score order' }).selectOption('shuffled')
  await expect(partials).toHaveCount(0)
})

test('checks wrong answers on a full finish without changing complete scoring', async ({ page }) => {
  await startOrdered(page)
  const cells = page.getByRole('textbox')
  for (let index = 0; index < await cells.count(); index++) {
    const [row, column] = (await cells.nth(index).getAttribute('aria-label'))!.split(' × ').map(Number)
    await cells.nth(index).fill(index === 0 ? '0' : String(row * column))
  }
  await expect(page.getByRole('button', { name: 'Finish early', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Finish', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Round complete', exact: true })).toBeVisible()
  await expect(page.getByText('143 / 144 correct', { exact: true })).toBeVisible()
  await expect(cells.nth(0)).toHaveAccessibleDescription('Incorrect. Correct: 1')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!).scores)
  expect(saved).toHaveLength(1)
  expect(saved[0]).toMatchObject({ status: 'complete', attempted: 144, correct: 143, total: 144, size: 12 })
  await expect(page.getByRole('table', { name: 'Partial results', exact: true })).toHaveCount(0)
})

test('does not save an unfinished round on reload', async ({ page }) => {
  await startOrdered(page)
  await page.getByRole('textbox').first().fill('0')
  await page.reload()
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBeNull()
  await expect(page.getByRole('heading', { name: 'Partial results' })).toHaveCount(0)
})

test('makes wrong attempted answers checkable without grading blanks', async ({ page }) => {
  await startOrdered(page)
  const correct = page.getByRole('textbox', { name: '1 × 1', exact: true })
  const wrong = page.getByRole('textbox', { name: '1 × 2', exact: true })
  const blank = page.getByRole('textbox', { name: '1 × 3', exact: true })
  await correct.fill('1')
  await wrong.fill('0')
  await expect(wrong).not.toHaveAttribute('aria-describedby')
  await page.getByRole('button', { name: 'Finish early', exact: true }).click()
  await expect(wrong).toHaveAccessibleDescription('Incorrect. Correct: 2')
  await expect(wrong.locator('..').getByText('Correct: 2', { exact: false })).toBeVisible()
  await expect(wrong.locator('..')).toHaveAttribute('data-result', 'incorrect')
  await expect(correct).toHaveAccessibleDescription('Correct.')
  await expect(correct.locator('..')).toHaveAttribute('data-result', 'correct')
  await expect(blank).toHaveValue('')
  await expect(blank).not.toHaveAttribute('aria-describedby')
  await expect(blank.locator('..')).not.toHaveAttribute('data-result')
  await page.screenshot({ path: 'artifacts/partial-result.png', fullPage: true })
})

test('finishes early only after an attempt and freezes an honestly labelled partial result', async ({ page }) => {
  await startOrdered(page)
  const cells = page.getByRole('textbox')
  await expect(page.getByRole('button', { name: 'Finish', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Finish early', exact: true })).toHaveCount(0)
  await cells.nth(0).fill('1')
  await expect(page.getByRole('button', { name: 'Finish early', exact: true })).toBeEnabled()
  await cells.nth(0).fill('')
  await expect(page.getByRole('button', { name: 'Finish', exact: true })).toBeDisabled()
  await cells.nth(0).fill('1')
  await cells.nth(1).fill('0')
  await expect(page.getByRole('region', { name: 'Round result' })).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBeNull()
  await page.getByRole('button', { name: 'Finish early', exact: true }).click()
  const result = page.getByRole('region', { name: 'Round result' })
  await expect(result.getByRole('heading', { name: 'Partial result', exact: true })).toBeVisible()
  await expect(result).toContainText('2 / 144 attempted')
  await expect(result).toContainText('1 / 2 correct')
  await expect(result).toContainText('50% accuracy')
  await expect(result).toContainText('142 unanswered cells are not graded.')
  const elapsed = await page.getByRole('timer').innerText()
  await page.waitForTimeout(250)
  await expect(page.getByRole('timer')).toHaveText(elapsed)
  await expect(cells.nth(0)).toHaveAttribute('readonly', '')
  await expect(cells.nth(2)).toHaveAttribute('readonly', '')
  await cells.nth(0).press('9')
  await expect(cells.nth(0)).toHaveValue('1')
  await expect(page.getByRole('button', { name: /^Finish/ })).toHaveCount(0)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!))
  expect(saved.version).toBe(3)
  expect(saved.scores).toHaveLength(1)
  expect(saved.scores[0]).toMatchObject({ status: 'partial', attempted: 2, correct: 1, size: 12, total: 144, mode: 'ordered' })
  await expect(page.getByText('No perfect round yet', { exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: 'High scores', exact: true })).toHaveCount(0)
})
