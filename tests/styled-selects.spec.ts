import { expect, test } from '@playwright/test'
import { chooseFilter } from './helpers'

for (const appearance of ['dark', 'light']) for (const width of [1024, 1440]) {
  test(`bounded readable custom-set menus in ${appearance} at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.addInitScript(({ appearance }) => {
      localStorage.setItem('times-tables.theme', appearance)
      const sets = Array.from({ length: 36 }, (_, index) => Array.from({ length: 20 }, (_, i) => i + 1).filter(value => value !== index % 20 + 1 && value !== Math.floor(index / 20) + 2))
      localStorage.setItem('times-tables.scores', JSON.stringify({ version: 4, scores: sets.map((factors, index) => ({ id: `set-${index}`, factors, mode: 'ordered', size: factors.length, total: factors.length ** 2, correct: 1, attempted: 1, status: 'partial', elapsedMs: 1000, completedAt: '2026-01-01T00:00:00Z' })) }))
    }, { appearance })
    await page.goto('/stats')
    for (const name of names) {
      const trigger = page.getByRole('combobox', { name, exact: true })
      await trigger.click()
      const panel = page.getByRole('listbox', { name: `${name} options`, exact: true })
      await expect(panel).toBeVisible()
      await expect(panel).toBeInViewport({ ratio: 1 })
      const box = await panel.boundingBox()
      expect(box!.height).toBeLessThanOrEqual(420)
      await page.screenshot({ path: info.outputPath(`${name.replaceAll(' ', '-')}.png`), fullPage: false })
      if (name.endsWith('size')) {
        const last = panel.getByRole('option').last()
        await page.keyboard.press('End')
        await expect(last).toBeFocused()
        await expect(last).toBeInViewport({ ratio: 1 })
        const geometry = await last.evaluate(element => ({ height: element.getBoundingClientRect().height, clipped: element.scrollWidth > element.clientWidth, whiteSpace: getComputedStyle(element).whiteSpace }))
        expect(geometry.clipped).toBe(false)
        expect(geometry.whiteSpace).toBe('normal')
        expect(geometry.height).toBeGreaterThan(36)
        await page.screenshot({ path: info.outputPath(`${name.replaceAll(' ', '-')}-scrolled.png`), fullPage: false })
      }
      await page.keyboard.press('Escape')
      await expect(panel).toHaveCount(0)
      await expect(trigger).toBeFocused()
    }
    const score = page.getByRole('combobox', { name: 'Stats size', exact: true })
    await chooseFilter(score, '2')
    await chooseFilter(score, '12')
    await expect(score).toHaveAttribute('data-value', '12')
    await page.reload()
    await expect(score).toHaveAttribute('data-value', '12')
    await expect(page.locator('select:visible')).toHaveCount(0)
  })
}


const names = ['Stats size']

test('keyboard settings and Tab dismissal preserve shared selection without playing the hidden round', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('textbox').first().fill('1')
  await page.getByRole('link', { name: 'Stats', exact: true }).click()
  const order = page.getByRole('radiogroup', { name: 'Stats order', exact: true })
  await order.getByRole('radio', { name: 'Ordered', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(order.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
  await expect(order.getByRole('radio', { name: 'Shuffled', exact: true })).toBeFocused()
  const trigger = page.getByRole('combobox', { name: 'Stats size', exact: true })
  await trigger.focus()
  await page.keyboard.press('Space')
  const panel = page.getByRole('listbox', { name: 'Stats size options', exact: true })
  await expect(panel).toBeVisible()
  for (const [key, index] of [['End', 10], ['Home', 0], ['ArrowDown', 1], ['ArrowUp', 0]] as const) {
    await page.keyboard.press(key)
    await expect(panel.getByRole('option').nth(index)).toBeFocused()
  }
  await page.keyboard.type('3')
  await expect(panel.locator('[data-value="3"]')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('data-value', '3')
  await trigger.press('Enter')
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('option', { selected: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(panel).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Run statistics', exact: true }).locator('dd').first()).toBeFocused()
  await trigger.press('Enter')
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('option', { selected: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(panel).toHaveCount(0)
  await expect(order.getByRole('radio', { name: 'Shuffled', exact: true })).toBeFocused()
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBeNull()
  await page.getByRole('link', { name: 'Practice', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible()
  await expect(page.getByRole('textbox').first()).toHaveValue('1')
  await page.getByRole('link', { name: 'Stats', exact: true }).click()
  await page.reload()
  await expect(trigger).toHaveAttribute('data-value', '3')
  await expect(order.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
})
test('one exact-settings picker uses a styled accessible panel without All choices', async ({ page }) => {
  await page.goto('/stats')
  await expect(page.locator('.score-heading')).toHaveText('Score history')
  await expect(page.getByRole('radiogroup', { name: 'Stats order', exact: true })).toHaveAttribute('data-value', 'shuffled')
  await expect(page.getByRole('combobox', { name: 'Stats size', exact: true })).toHaveAttribute('data-value', '12')
  for (const name of names) {
    const trigger = page.getByRole('combobox', { name, exact: true })
    await expect(trigger).toHaveJSProperty('tagName', 'BUTTON')
    await trigger.click()
    const panel = page.getByRole('listbox', { name: `${name} options`, exact: true })
    await expect(panel).toBeVisible()
    await expect(panel.getByRole('option').first()).toBeVisible()
    await expect(panel.getByRole('option', { name: /all/i })).toHaveCount(0)
    await page.keyboard.press('Escape')
    await expect(panel).toHaveCount(0)
    await expect(trigger).toBeFocused()
  }
  await expect(page.locator('select:visible')).toHaveCount(0)
})
