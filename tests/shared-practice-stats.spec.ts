import { expect, test } from '@playwright/test'
import { chooseFilter, chooseGridSize, showPractice, showStats } from './helpers'

test('shared controls stay locked through a delayed score save, then a changed setting resets only the finished display', async ({ page, context }) => {
  await page.goto('/')
  await chooseGridSize(page, 2)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('textbox').first().fill('1')
  const holder = await context.newPage()
  await holder.goto('/')
  await holder.evaluate(async () => {
    let ready!: () => void
    const acquired = new Promise<void>(resolve => { ready = resolve })
    void navigator.locks.request('times-tables.scores', () => new Promise<void>(resolve => { Object.assign(window, { releaseSaveLock: resolve }); ready() }))
    await acquired
  })
  await page.keyboard.press('Shift+Enter')
  await showStats(page)
  const picker = page.getByRole('combobox', { name: 'Stats size', exact: true })
  await expect(picker).toBeDisabled()
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeDisabled()
  await holder.evaluate(() => (window as unknown as { releaseSaveLock: () => void }).releaseSaveLock())
  await expect(picker).toBeEnabled()
  const raw = await page.evaluate(() => localStorage.getItem('times-tables.scores'))
  await chooseFilter(picker, '4')
  await showPractice(page)
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  await expect(page.getByRole('textbox')).toHaveCount(16)
  await expect(page.getByRole('textbox').first()).toHaveValue('')
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBe(raw)
  await holder.close()
})

test('an empty custom practice selection remains honestly empty in Stats and can select a preset', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('times-tables.settings', JSON.stringify({ version: 1, mode: 'ordered', size: 2, choice: 'custom', customFactors: [] })))
  await page.reload()
  await showStats(page)
  const picker = page.getByRole('combobox', { name: 'Stats size', exact: true })
  await expect(picker).toHaveText('None')
  await expect(page.locator('.run-statistics dd')).toHaveText(['0', '0', '—', '—'])
  await expect(page.locator('.progress-empty')).toHaveText('No rounds for Ordered · None.')
  await chooseFilter(picker, '2')
  await showPractice(page)
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('2 × 2')
})

test('Practice and Stats share exact order and factors bidirectionally without changing an active run', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => {
    localStorage.setItem('times-tables.settings', JSON.stringify({ version: 1, mode: 'ordered', size: 2, choice: 'custom', customFactors: [2, 7], scoreMode: 'all', retained: true }))
    localStorage.setItem('times-tables.progress', JSON.stringify({ version: 1, mode: 'shuffled', size: 4, axisMode: 'time', retained: true }))
  })
  await page.reload()
  await showStats(page)
  const size = page.getByRole('combobox', { name: 'Stats size', exact: true })
  await expect(size).toHaveAttribute('data-value', 'set:2,7')
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeChecked()
  await chooseFilter(size, '3')
  await page.getByRole('radio', { name: 'Shuffled', exact: true }).click()
  await showPractice(page)
  await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('3 × 3')
  await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
  await chooseGridSize(page, 2)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('textbox').first().fill('1')
  await showStats(page)
  await expect(size).toHaveAttribute('data-value', '2')
  await expect(size).toBeDisabled()
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeDisabled()
  await showPractice(page)
  await expect(page.getByRole('textbox').first()).toHaveValue('1')
  await page.getByRole('textbox').first().press('Shift+Enter')
  await expect(page.getByRole('heading', { name: 'Partial result' })).toBeVisible()
  const before = await page.evaluate(() => localStorage.getItem('times-tables.scores'))
  await showStats(page)
  await expect(size).toBeEnabled()
  await chooseFilter(size, 'set:2,7')
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await showPractice(page)
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('Custom')
  await expect(page.getByRole('textbox')).toHaveCount(4)
  await expect(page.getByRole('textbox').first()).toHaveValue('')
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBe(before)
  await page.getByRole('button', { name: 'Grid size', exact: true }).click()
  const custom = page.getByRole('dialog', { name: 'Grid size options', exact: true })
  for (const value of [2, 7, 3, 8]) await custom.getByRole('button', { name: String(value), exact: true }).click()
  await custom.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(custom).toHaveCount(0)
  await showStats(page)
  await expect(size).toHaveAttribute('data-value', 'set:3,8')
  await page.reload()
  await showStats(page)
  await expect(size).toHaveAttribute('data-value', 'set:3,8')
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeChecked()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.progress')!))).toEqual({ version: 1, mode: 'shuffled', size: 4, axisMode: 'time', retained: true })
})
