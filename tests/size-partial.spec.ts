import { expect, test } from '@playwright/test'
import { chooseGridSize } from './helpers'

test('small partial rounds retain keyboard controls and size-specific records after reset and Escape', async ({ page }) => {
  await page.goto('/')
  const size = page.getByRole('button', { name: 'Grid size', exact: true })
  const start = page.getByRole('button', { name: 'Start', exact: true })
  const cells = page.getByRole('textbox')
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await chooseGridSize(page, 2)
  await page.getByRole('heading', { name: 'Times tables' }).click()
  await page.keyboard.press('Enter')
  await expect(cells).toHaveCount(4)
  await expect(size).toBeDisabled()
  await cells.nth(0).fill('1')
  await cells.nth(0).press('Space')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('ArrowRight')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('ArrowDown')
  await expect(cells.nth(3)).toBeFocused()
  await cells.nth(3).press('Space')
  await expect(cells.nth(3)).toBeFocused()
  await page.getByRole('button', { name: 'Finish early', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Round result' })).toContainText('1 / 4 attempted')
  const saved = await page.evaluate(() => localStorage.getItem('times-tables.scores'))
  expect(JSON.parse(saved!).scores).toEqual([expect.objectContaining({ size: 2, total: 4, attempted: 1, correct: 1, status: 'partial' })])
  await page.getByRole('button', { name: 'New round', exact: true }).click()
  await expect(start).toBeFocused()
  await expect(size).toBeEnabled()
  await page.keyboard.press('Space')
  await expect(cells.nth(0)).toBeFocused()
  await cells.nth(0).fill('2')
  await page.keyboard.press('Escape')
  await expect(start).toBeFocused()
  await expect(size).toBeEnabled()
  await expect(page.getByRole('timer')).toHaveText('0:00.0')
  await expect(cells.nth(0)).toHaveValue('')
  await chooseGridSize(page, 3)
  await expect(page.getByRole('table', { name: 'Score history', exact: true })).toBeVisible()
  await page.getByRole('heading', { name: 'Times tables' }).click()
  await page.keyboard.press('Space')
  await expect(cells).toHaveCount(9)
  await cells.nth(8).fill('9')
  await page.keyboard.press('Escape')
  await expect(start).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(cells.nth(8)).toHaveValue('')
  await cells.nth(8).fill('9')
  await expect(cells.nth(8)).toHaveValue('9')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await chooseGridSize(page, 2)
  await expect(page.getByRole('table', { name: 'Score history', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBe(saved)
})

test('saves a small early finish separately from migrated complete scores across reloads', async ({ page }) => {
  await page.goto('/')
  const legacy = { id: 'small-complete', mode: 'ordered', size: 2, total: 4, correct: 4, elapsedMs: 1000, completedAt: '2026-01-01T00:00:00.000Z' }
  await page.evaluate(score => localStorage.setItem('times-tables.scores', JSON.stringify({ version: 2, scores: [score] })), legacy)
  await page.reload()
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await chooseGridSize(page, 2)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  const cells = page.getByRole('textbox')
  await cells.nth(0).fill('1')
  await cells.nth(1).fill('0')
  await page.getByRole('button', { name: 'Finish early', exact: true }).click()
  const result = page.getByRole('region', { name: 'Round result' })
  await expect(result).toContainText('2 / 4 attempted')
  await expect(result).toContainText('1 / 2 correct')
  await expect(result).toContainText('50% accuracy')
  await expect(result).toContainText('2 unanswered cells are not graded.')
  await expect(cells.nth(1)).toHaveAccessibleDescription('Incorrect. Correct: 2')
  await expect(cells.nth(2)).not.toHaveAttribute('aria-describedby')
  await expect(cells.nth(2).locator('..')).not.toHaveAttribute('data-result')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!))
  expect(saved.version).toBe(3)
  expect(saved.scores).toHaveLength(2)
  expect(saved.scores[0]).toEqual({ ...legacy, status: 'complete', attempted: 4 })
  expect(saved.scores[1]).toMatchObject({ size: 2, total: 4, status: 'partial', attempted: 2, correct: 1 })
  await page.reload()
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  const partials = page.getByRole('table', { name: 'Score history', exact: true }).getByRole('row').filter({ has: page.getByRole('cell', { name: 'Partial', exact: true }) })
  await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('2 × 2')
  await expect(partials).toHaveCount(1)
  await expect(partials).toContainText('2 / 4')
  await expect(partials).toContainText('50%')
  const full = page.getByRole('table', { name: 'Score history', exact: true }).getByRole('row').filter({ has: page.getByRole('cell', { name: 'Complete', exact: true }) })
  await expect(full).toHaveCount(1)
  await expect(full).toContainText('4 / 4')
  await expect(page.getByText('Fastest perfect: 0:01.0', { exact: true })).toBeVisible()
  await page.getByRole('radio', { name: 'Shuffled', exact: true }).click()
  await expect(full).toHaveCount(1)
  await expect(page.getByText('No perfect round yet', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Score order' }).selectOption('shuffled')
  await expect(partials).toHaveCount(0)
  await expect(full).toHaveCount(0)
  await expect(page.getByText('No perfect round yet', { exact: true })).toBeVisible()
})
