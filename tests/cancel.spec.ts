import { expect, test } from '@playwright/test'
import { SCORE_KEY } from '../src/scores'

test('cancel discards a running round without changing saved scores', async ({ page }) => {
  const saved = JSON.stringify({ version: 1, scores: [{
    id: 'previous-round', mode: 'shuffled', correct: 144, total: 144,
    elapsedMs: 20000, completedAt: '2026-01-02T12:00:00.000Z',
  }] })
  await page.clock.install({ time: new Date('2026-01-02T12:00:00Z') })
  await page.goto('/')
  await page.evaluate(({ key, value }) => localStorage.setItem(key, value), { key: SCORE_KEY, value: saved })
  await page.reload()
  await page.clock.pauseAt(new Date('2026-01-02T12:01:00Z'))
  const cancel = page.getByRole('button', { name: 'Cancel', exact: true })
  const cells = page.getByRole('textbox')
  const scores = page.getByRole('table', { name: 'Score history' })
  await expect(cancel).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'New round', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(cancel).toBeVisible()
  await cells.first().fill('123')
  await cells.last().fill('45')
  await page.clock.runFor(5000)
  await expect(page.getByRole('timer')).toHaveText('0:05.0')
  await cancel.click()
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  await expect(cancel).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Round result' })).toHaveCount(0)
  await expect(page.getByText('0 / 144 filled', { exact: true })).toBeVisible()
  expect(await cells.evaluateAll(inputs => inputs.every(input => (input as HTMLInputElement).value === '' && (input as HTMLInputElement).disabled))).toBe(true)
  await expect(page.getByRole('columnheader').filter({ hasText: /^\d+$/ })).toHaveCount(0)
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeEnabled()
  await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeEnabled()
  await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
  await expect(page.getByRole('button', { name: 'Finish', exact: true })).toBeDisabled()
  await page.clock.runFor(10000)
  await expect(page.getByRole('timer')).toHaveText('0:00.0')
  await expect(scores.getByRole('row')).toHaveCount(2)
  expect(await page.evaluate(key => localStorage.getItem(key), SCORE_KEY)).toBe(saved)

  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(cells.first()).toBeFocused()
  await expect(cells.first()).toHaveValue('')
  await cells.first().fill('1')
  await cells.first().press('Space')
  await expect(cells.nth(1)).toBeFocused()
  await page.clock.runFor(1000)
  await expect(page.getByRole('timer')).toHaveText('0:01.0')
  expect(await page.evaluate(key => localStorage.getItem(key), SCORE_KEY)).toBe(saved)
})

test('new round clears a completed result while preserving its saved score', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-01-02T12:00:00Z') })
  await page.goto('/')
  await page.clock.pauseAt(new Date('2026-01-02T12:01:00Z'))
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  const newRound = page.getByRole('button', { name: 'New round', exact: true })
  const cells = page.getByRole('textbox')
  const scores = page.getByRole('table', { name: 'Score history' })
  await expect(newRound).toHaveCount(0)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(newRound).toHaveCount(0)
  for (let index = 0; index < 144; index++) {
    const label = await cells.nth(index).getAttribute('aria-label')
    const [row, column] = label!.split(' × ').map(Number)
    await cells.nth(index).fill(String(row * column))
  }
  await page.clock.runFor(5000)
  await page.getByRole('button', { name: 'Finish', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Round result' })).toBeVisible()
  await expect(page.getByText('144 / 144 correct', { exact: true })).toBeVisible()
  await expect(page.getByRole('timer')).toHaveText('0:05.0')
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toHaveCount(0)
  await expect(newRound).toBeVisible()
  const saved = await page.evaluate(key => localStorage.getItem(key), SCORE_KEY)
  expect(JSON.parse(saved!).scores).toHaveLength(1)

  await newRound.click()
  await expect(newRound).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Round result' })).toHaveCount(0)
  await expect(page.getByText('0 / 144 filled', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  expect(await cells.evaluateAll(inputs => inputs.every(input => (input as HTMLInputElement).value === '' && (input as HTMLInputElement).disabled && !(input as HTMLInputElement).readOnly))).toBe(true)
  await expect(page.getByRole('columnheader').filter({ hasText: /^\d+$/ })).toHaveCount(0)
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeEnabled()
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeChecked()
  await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeEnabled()
  await page.clock.runFor(10000)
  await expect(page.getByRole('timer')).toHaveText('0:00.0')
  await expect(scores.getByRole('row')).toHaveCount(2)
  await expect(page.getByText('Fastest perfect: 0:05.0', { exact: true })).toBeVisible()
  expect(await page.evaluate(key => localStorage.getItem(key), SCORE_KEY)).toBe(saved)

  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(cells.first()).toBeFocused()
  await cells.first().fill('1')
  await expect(page.getByText('1 / 144 filled', { exact: true })).toBeVisible()
  await page.clock.runFor(1000)
  await expect(page.getByRole('timer')).toHaveText('0:01.0')
  await page.reload()
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await expect(scores.getByRole('row')).toHaveCount(2)
  expect(await page.evaluate(key => localStorage.getItem(key), SCORE_KEY)).toBe(saved)
})
