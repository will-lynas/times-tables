import { expect, test, type Page } from '@playwright/test'
import { chooseFilter, chooseGridSize, showPractice, showStats } from './helpers'

for (const failure of ['getter', 'write'] as const) {
  test(`unavailable storage ${failure} keeps settings playable without falsely claiming a score was saved`, async ({ page }) => {
    await page.addInitScript(failure => {
      if (failure === 'getter') Object.defineProperty(window, 'localStorage', {
        get() { throw new DOMException('Blocked', 'SecurityError') },
      })
      else Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError') }
    }, failure)
    await page.goto('/')
    await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
    await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('12 × 12')
    await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
    await chooseGridSize(page, 2)
    await completeGrid(page)
    await expect(page.getByRole('alert').filter({ hasText: 'Score not saved' })).toBeVisible()
    await expect(page.getByText('Score saved in this browser.', { exact: true })).toHaveCount(0)
    await showStats(page)
    await expect(page.getByRole('table', { name: 'Score history', exact: true })).toContainText('4 / 4')
    await page.reload()
    await showPractice(page)
    await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
    await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('12 × 12')
  })
}


test('shows every saved setting after refresh with independent history filters and no top-five truncation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await chooseGridSize(page, 2)
  await completeGrid(page)
  await page.getByRole('button', { name: 'New round' }).click()
  await page.getByRole('radio', { name: 'Shuffled', exact: true }).click()
  await chooseGridSize(page, 3)
  await completeGrid(page)
  await page.getByRole('button', { name: 'New round' }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('textbox').first().fill('0')
  await page.getByRole('button', { name: 'Finish early' }).click()
  await expect(page.getByRole('heading', { name: 'Partial result', exact: true })).toBeVisible()
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!))
  await page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('times-tables.scores')!)
    for (let index = 0; index < 7; index++) data.scores.push({ ...data.scores[0], id: `historical-${index}` })
    localStorage.setItem('times-tables.scores', JSON.stringify(data))
  })
  await page.reload()
  const raw = await page.evaluate(() => localStorage.getItem('times-tables.scores'))
  const history = page.getByRole('table', { name: 'Score history', exact: true })
  const full = history.getByRole('row').filter({ has: page.getByRole('cell', { name: 'Complete', exact: true }) })
  await showStats(page)
  await expect(history.getByRole('row')).toHaveCount(11)
  await expect(full).toHaveCount(9)
  await expect(full.filter({ hasText: 'Ordered' }).filter({ hasText: '2 × 2' })).toHaveCount(8)
  await expect(full.filter({ hasText: 'Shuffled' }).filter({ hasText: '3 × 3' })).toHaveCount(1)
  const partials = history.getByRole('row').filter({ has: page.getByRole('cell', { name: 'Partial', exact: true }) })
  await expect(partials).toHaveCount(1)
  await expect(partials).toContainText('Partial')
  await expect(partials).toContainText('Shuffled')
  await expect(partials).toContainText('3 × 3')
  const order = page.getByRole('combobox', { name: 'Score order', exact: true })
  const size = page.getByRole('combobox', { name: 'Score size', exact: true })
  await expect(order).toHaveAttribute('data-value', 'all')
  await expect(size).toHaveAttribute('data-value', 'all')
  await chooseFilter(order, 'ordered')
  await expect(full).toHaveCount(8)
  await expect(partials).toHaveCount(0)
  await chooseFilter(size, '3')
  await expect(full).toHaveCount(0)
  await expect(page.getByText('No rounds match these filters.', { exact: true })).toBeVisible()
  await chooseFilter(order, 'shuffled')
  await expect(full).toHaveCount(1)
  await expect(history.getByRole('row')).toHaveCount(3)
  await expect(partials).toHaveCount(1)
  await showPractice(page)
  await chooseGridSize(page, 12)
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await page.getByRole('button', { name: 'Switch to light mode' }).click()
  await showStats(page)
  await expect(full).toHaveCount(1)
  await expect(history.getByRole('row')).toHaveCount(3)
  await expect(full).toContainText('Shuffled')
  await page.reload()
  await expect(order).toHaveAttribute('data-value', 'shuffled')
  await expect(size).toHaveAttribute('data-value', '3')
  await showPractice(page)
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeChecked()
  await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText('12 × 12')
  await expect(page.locator('.radix-themes')).toHaveClass(/light/)
  await showStats(page)
  await expect(full).toHaveCount(1)
  await expect(history.getByRole('row')).toHaveCount(3)
  await chooseFilter(order, 'all')
  await chooseFilter(size, 'all')
  await expect(history.getByRole('row')).toHaveCount(11)
  await expect(full).toHaveCount(9)
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBe(raw)
  await page.locator('.scores').first().screenshot({ path: 'artifacts/score-history-light.png' })
  await completeGrid(page)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!))
  expect(saved.scores).toHaveLength(11)
  expect(saved.scores.slice(0, 3)).toEqual(original.scores)
  expect(saved.scores.slice(0, 10)).toEqual(JSON.parse(raw!).scores)
})

async function completeGrid(page: Page) {
  await showPractice(page)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  const cells = page.getByRole('textbox')
  for (let index = 0; index < await cells.count(); index++) {
    const [row, column] = (await cells.nth(index).getAttribute('aria-label'))!.split(' × ').map(Number)
    await cells.nth(index).fill(String(row * column))
  }
  await page.getByRole('button', { name: 'Finish', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Round complete', exact: true })).toBeVisible()
}

for (const [mode, size] of [['Ordered', 12], ['Shuffled', 2], ['Ordered', 2]] as const) {
  test(`refresh retains ${mode} ${size} × ${size} scores and can complete another round`, async ({ page }) => {
    await page.goto('/')
    await page.getByRole('radio', { name: mode, exact: true }).click()
    await chooseGridSize(page, size)
    await completeGrid(page)
    const before = await page.evaluate(() => localStorage.getItem('times-tables.scores'))
    const heading = 'Score history'
    await showStats(page)
    await expect(page.getByRole('table', { name: heading, exact: true })).toBeVisible()
    await page.reload()
    const after = await page.evaluate(() => localStorage.getItem('times-tables.scores'))
    console.log(JSON.stringify({ mode, size, before, after, headingAfterRefresh: await page.locator('#scores-heading').innerText() }))
    expect(after).toBe(before)
    await showPractice(page)
    await expect(page.getByRole('radio', { name: mode, exact: true })).toBeChecked()
    await expect(page.getByRole('button', { name: 'Grid size', exact: true })).toHaveText(`${size} × ${size}`)
    await showStats(page)
    await expect(page.getByRole('table', { name: heading, exact: true }).getByRole('row')).toHaveCount(2)
    await showPractice(page)
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeFocused()
    await completeGrid(page)
    await expect(page.getByText(`${size * size} / ${size * size} filled`, { exact: true })).toBeVisible()
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('times-tables.scores')!))
    expect(saved.scores).toHaveLength(2)
    expect(saved.scores[0]).toEqual(JSON.parse(before!).scores[0])
    expect(saved.scores[1]).toMatchObject({ mode: mode.toLowerCase(), size, status: 'complete', attempted: size * size, correct: size * size, total: size * size })
  })
}
