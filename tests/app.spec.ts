import { expect, test, type Page } from '@playwright/test'
import { chooseGridSize } from './helpers'

test('keeps functional cues without explanatory filler', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('times-tables.scores', '{broken'))
  await page.goto('/')
  const filler = /One grid\. A little faster each time\.|The grid is revealed when you start\.|The timer won’t pause\.|Your finished grid stays here for review\.|All completed rounds, newest first\.|Personal bests compare only matching order and size\.|All matching partial results, newest first\./
  await expect(page.locator('main')).not.toContainText(filler)
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toHaveAccessibleDescription('Enter or Space to start')
  await expect(page.getByRole('alert')).toContainText('Saved scores could not be read.')
  await expect(page.getByText('Scores stay in this browser only.', { exact: true })).toHaveCount(0)
  await expect(page.getByText('No rounds yet.', { exact: true })).toBeVisible()
  await chooseGridSize(page, 2)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(page.locator('.grid-footer')).toContainText('Esc cancel')
  await expect(page.locator('.grid-footer')).toContainText('Shift + Tab back')
  await expect(page.locator('.grid-footer')).toContainText('Arrow keys move')
  await page.getByRole('textbox').first().fill('0')
  await page.getByRole('button', { name: 'Finish early' }).click()
  await expect(page.getByRole('region', { name: 'Round result' })).toContainText('Partial result')
  await expect(page.getByRole('region', { name: 'Round result' })).toContainText('1 / 4 attempted')
  await expect(page.locator('main')).not.toContainText(filler)
  await expect(page.getByRole('textbox').first()).toHaveAccessibleDescription(/^Incorrect\. Correct:/)
})

async function startOrdered(page: Page) {
  await page.goto('/')
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
}

async function fillGrid(page: Page, wrong = false) {
  const cells = page.getByRole('textbox')
  for (let index = 0; index < 144; index++) {
    const label = await cells.nth(index).getAttribute('aria-label')
    const [row, column] = label!.split(' × ').map(Number)
    await cells.nth(index).fill(index === 0 && wrong ? '0' : String(row * column))
  }
}

test('finishes only explicitly, freezes a perfect result and persists its score on reload', async ({ page }) => {
  await startOrdered(page)
  await fillGrid(page)
  await expect(page.getByRole('button', { name: 'Finish', exact: true })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'Round complete', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Finish', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Round complete', exact: true })).toBeVisible()
  await expect(page.getByText('144 / 144 correct', { exact: true })).toBeVisible()
  await expect(page.getByText('100% accuracy', { exact: true })).toBeVisible()
  const elapsed = await page.getByRole('timer').innerText()
  await page.waitForTimeout(250)
  await expect(page.getByRole('timer')).toHaveText(elapsed)
  await expect(page.getByRole('textbox').first()).toHaveAttribute('readonly', '')
  await expect(page.getByText('Score saved in this browser.', { exact: true })).toBeVisible()
  await expect(page.getByText(`Fastest perfect: ${elapsed}`, { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('radio', { name: 'Ordered', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Score history' }).getByRole('row')).toHaveCount(2)
  await expect(page.getByText(`Fastest perfect: ${elapsed}`, { exact: true })).toBeVisible()
})

test('supports numeric editing and keyboard navigation without submitting', async ({ page }) => {
  await startOrdered(page)
  const cells = page.getByRole('textbox')
  await cells.nth(0).pressSequentially('a-1.2e')
  await expect(cells.nth(0)).toHaveValue('12')
  await expect(page.getByText('1 / 144 filled', { exact: true })).toBeVisible()
  await cells.nth(0).press('Space')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('Tab')
  await expect(cells.nth(2)).toBeFocused()
  await cells.nth(2).press('Shift+Tab')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('ArrowDown')
  await expect(cells.nth(13)).toBeFocused()
  await cells.nth(13).press('ArrowRight')
  await expect(cells.nth(14)).toBeFocused()
  await cells.nth(14).press('ArrowUp')
  await expect(cells.nth(2)).toBeFocused()
  await cells.nth(2).press('ArrowLeft')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(0).click()
  await cells.nth(0).fill('1')
  await expect(cells.nth(0)).toHaveValue('1')
  await cells.nth(0).press('ArrowLeft')
  await expect(cells.nth(0)).toBeFocused()
  await cells.nth(11).click()
  await cells.nth(11).press('ArrowRight')
  await expect(cells.nth(11)).toBeFocused()
  await cells.nth(143).fill('144')
  await expect(page.getByRole('button', { name: 'Finish early', exact: true })).toBeEnabled()
})

test('starts a hidden shuffled grid only on request and runs an unpausable timer', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveTitle('Times tables')
  await expect(page.getByRole('radio', { name: 'Shuffled', exact: true })).toBeChecked()
  await expect(page.getByRole('textbox')).toHaveCount(144)
  await expect(page.getByRole('textbox').first()).toBeDisabled()
  await expect(page.getByRole('columnheader').filter({ hasText: /^\d+$/ })).toHaveCount(0)
  await expect(page.getByRole('timer')).toHaveText('0:00.0')
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(page.getByRole('textbox').first()).toBeFocused()
  await expect(page.getByRole('radio', { name: 'Ordered', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Finish', exact: true })).toBeDisabled()
  await expect(page.getByRole('columnheader').filter({ hasText: /^\d+$/ })).toHaveCount(12)
  await expect(page.getByRole('timer')).not.toHaveText('0:00.0')
  const elapsed = await page.getByRole('timer').innerText()
  await page.locator('body').click({ position: { x: 8, y: 8 } })
  await expect(page.getByRole('timer')).not.toHaveText(elapsed)
})
