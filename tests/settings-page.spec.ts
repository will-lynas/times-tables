import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { chooseGridSize } from './helpers'

const key = 'times-tables.settings'

for (const source of [null, ' {"version":1,"size":2,"mode":"ordered","unknown":{"kept":true}} ']) test(`Space is inert by default without rewriting ${source === null ? 'missing' : 'legacy'} settings`, async ({ page }) => {
  await page.goto('/')
  if (source !== null) await page.evaluate(({ key, source }) => localStorage.setItem(key, source), { key, source })
  await page.reload()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  const cells = page.getByRole('textbox')
  await cells.first().fill('1')
  const scroll = await page.evaluate(() => window.scrollY)
  await cells.first().press('Space')
  await expect(cells.first()).toBeFocused()
  await expect(cells.first()).toHaveValue('1')
  expect(await page.evaluate(() => window.scrollY)).toBe(scroll)
  await expect(page.locator('.grid-footer')).not.toContainText('Space')
  expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe(source)
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Space to advance', exact: true })).not.toBeChecked()
})

test('Settings toggles live navigation without resetting answers or timer and persists explicit off', async ({ page }) => {
  await page.goto('/')
  await chooseGridSize(page, 2)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  const cells = page.getByRole('textbox')
  await cells.first().fill('1')
  const before = await page.getByRole('timer').innerText()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  const toggle = page.getByRole('switch', { name: 'Space to advance', exact: true })
  await expect(toggle).not.toBeChecked()
  await toggle.focus()
  await toggle.press('Space')
  await expect(toggle).toBeChecked()
  await page.locator('body').click({ position: { x: 8, y: 8 } })
  for (const shortcut of ['Enter', 'Shift+Enter', 'Space', 'Escape']) await page.keyboard.press(shortcut)
  await page.waitForTimeout(250)
  await page.goBack()
  await expect(cells.first()).toHaveValue('1')
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible()
  expect(await page.getByRole('timer').innerText()).not.toBe(before)
  await expect(page.locator('.grid-footer')).toContainText('Space / Tab next')
  await cells.first().press('Space')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('Enter')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('Tab')
  await expect(cells.nth(2)).toBeFocused()
  await cells.nth(2).press('Shift+Tab')
  await expect(cells.nth(1)).toBeFocused()
  await cells.nth(1).press('ArrowDown')
  await expect(cells.last()).toBeFocused()
  await cells.last().press('Space')
  await expect(cells.last()).toBeFocused()
  expect(await page.evaluate(() => localStorage.getItem('times-tables.scores'))).toBeNull()
  await page.goForward()
  await toggle.click()
  await expect(toggle).not.toBeChecked()
  await page.getByRole('link', { name: 'Practice', exact: true }).click()
  await cells.first().press('Space')
  await expect(cells.first()).toBeFocused()
  await cells.first().press('Shift+Enter')
  await expect(page.getByRole('region', { name: 'Round result' })).toBeVisible()
  await page.getByRole('button', { name: 'New round', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).press('Space')
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible()
  await cells.first().press('Escape')
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  await page.goto('/settings')
  await page.reload()
  await expect(toggle).not.toBeChecked()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).spaceToAdvance, key)).toBe(false)
})

for (const interruption of ['reload', 'close']) test(`Space toggle survives immediate ${interruption} while another tab holds its settings lock`, async ({ page, context }) => {
  await page.goto('/settings')
  const holder = await context.newPage()
  await holder.goto('/')
  await holder.evaluate(async () => {
    let acquired!: () => void
    const ready = new Promise<void>(resolve => { acquired = resolve })
    void navigator.locks.request('times-tables.settings', () => new Promise<void>(resolve => {
      Object.assign(window, { releaseStorageLock: resolve }); acquired()
    }))
    await ready
  })
  await page.getByRole('switch', { name: 'Space to advance', exact: true }).click()
  if (interruption === 'reload') await page.reload({ waitUntil: 'commit' })
  else {
    await page.close()
    page = await context.newPage()
    await page.goto('/settings', { waitUntil: 'commit' })
  }
  await holder.evaluate(() => (window as unknown as { releaseStorageLock: () => void }).releaseStorageLock())
  await expect(page.getByRole('switch', { name: 'Space to advance', exact: true })).toBeChecked()
  await holder.close()
  await page.getByRole('link', { name: 'Practice', exact: true }).click()
  await chooseGridSize(page, 2)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('textbox').first().press('Space')
  await expect(page.getByRole('textbox').nth(1)).toBeFocused()
  await page.reload()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('textbox').first().press('Space')
  await expect(page.getByRole('textbox').nth(1)).toBeFocused()
})

for (const appearance of ['dark', 'light']) for (const width of [1024, 1440]) {
  test(`Settings direct/reload/back/forward and ready scoping at ${width} ${appearance}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.addInitScript(appearance => localStorage.setItem('times-tables.theme', appearance), appearance)
    await page.goto('/settings')
    await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
    const toggle = page.getByRole('switch', { name: 'Space to advance', exact: true })
    await expect(toggle).not.toBeChecked()
    await page.locator('body').click({ position: { x: 8, y: 8 } })
    for (const shortcut of ['Enter', 'Shift+Enter', 'Space', 'Escape']) await page.keyboard.press(shortcut)
    await page.reload()
    await expect(toggle).not.toBeChecked()
    await mkdir('artifacts/settings', { recursive: true })
    await page.screenshot({ path: `artifacts/settings/settings-${width}-${appearance}.png`, fullPage: true })
    await toggle.focus()
    await toggle.press('Enter')
    await expect(toggle).toBeChecked()
    await page.getByRole('link', { name: 'Practice', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
    await page.goBack()
    await expect(toggle).toBeChecked()
    await page.goForward()
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  })
}

test('unsaved setting reports storage failure and retains original bytes', async ({ page }) => {
  await page.goto('/settings')
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key.startsWith('times-tables.settings')) throw new DOMException('Full', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await page.getByRole('switch', { name: 'Space to advance', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText(/could not|not.*sav|cannot/i)
  expect(await page.evaluate(key => localStorage.getItem(key), key)).toBeNull()
  await page.reload()
  await expect(page.getByRole('switch', { name: 'Space to advance', exact: true })).not.toBeChecked()
})
